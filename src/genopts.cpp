/*! \file
  wxmaxima-genopts: writes everything that describes wxMaxima's command line
  from the one table in CommandLineOptions.h.

  It is a build-time tool, not part of wxMaxima: it uses no wxWidgets, so it
  builds and runs without a display, which running wxMaxima itself (whose
  main() starts the GUI before it parses its arguments) would not.

  Usage:
    wxmaxima-genopts bash OUTFILE        bash completion
    wxmaxima-genopts zsh OUTFILE         zsh completion
    wxmaxima-genopts fish OUTFILE        fish completion
    wxmaxima-genopts man TEMPLATE OUTFILE
        copies TEMPLATE, replacing the line that contains the marker
        "WXMAXIMA-GENERATED-OPTIONS" by the man page's option list
    wxmaxima-genopts check FILE...
        fails if a FILE does not mention every long option. For documents
        that are written (and translated) by hand.
*/

#include "CommandLineOptions.h"

#include <cctype>
#include <fstream>
#include <initializer_list>
#include <iostream>
#include <sstream>
#include <string>
#include <string_view>
#include <vector>

using namespace wxm::cmdline;

namespace {

//! The commands the completions are registered for: wxmxdiff is a symlink
//! to wxmaxima that starts in diff mode, and takes the same options.
constexpr std::array<std::string_view, 2> CommandNames{"wxmaxima",
                                                       "wxmxdiff"};

//! Replaces every occurrence of \p from in \p text by \p to
std::string ReplaceAll(std::string_view text, std::string_view from,
                       std::string_view to) {
  std::string result;
  std::size_t pos = 0;
  while (true) {
    const std::size_t hit = text.find(from, pos);
    if (hit == std::string_view::npos)
      break;
    result.append(text.substr(pos, hit - pos));
    result.append(to);
    pos = hit + from.size();
  }
  result.append(text.substr(pos));
  return result;
}

//! \p text as a single-quoted POSIX shell word (bash, zsh)
std::string ShellQuote(std::string_view text) {
  return "'" + ReplaceAll(text, "'", "'\\''") + "'";
}

//! The openable extensions as an extglob/zsh alternation: "wxm|wxmx|..."
std::string ExtensionAlternation() {
  std::string result;
  for (const auto &ext : OpenableExtensions) {
    if (!result.empty())
      result += '|';
    result += ext;
  }
  return result;
}

std::string Bash() {
  std::ostringstream out;
  out << "# bash completion for wxmaxima(1)                -*- shell-script -*-\n"
         "# Generated by wxmaxima-genopts from src/CommandLineOptions.h:\n"
         "# change the options there, not here.\n\n"
         "_wxmaxima()\n"
         "{\n"
         "    local cur prev words cword split\n"
         "    _init_completion -s || return\n\n"
         "    case $prev in\n";
  // One case branch per kind of value, listing every spelling that takes it.
  const auto branch = [&out](Complete what, std::string_view action) {
    std::string names;
    for (const auto &opt : Options) {
      if (opt.kind != Kind::Option || opt.complete != what)
        continue;
      if (!opt.shortName.empty())
        names += (names.empty() ? "" : "|") + std::string("-") +
                 std::string(opt.shortName);
      names += (names.empty() ? "" : "|") + std::string("--") +
               std::string(opt.longName);
    }
    if (!names.empty())
      out << "        " << names << ")\n            " << action
          << "\n            return\n            ;;\n";
  };
  branch(Complete::Openable, "_filedir '@(" + ExtensionAlternation() + ")'");
  branch(Complete::AnyFile, "_filedir");
  branch(Complete::Nothing, ":");
  out << "    esac\n\n"
         "    $split && return\n\n"
         "    if [[ $cur == -* ]]; then\n"
         "        COMPREPLY=( $(compgen -W '";
  bool first = true;
  for (const auto &opt : Options) {
    if (!first)
      out << ' ';
    first = false;
    if (!opt.shortName.empty())
      out << '-' << opt.shortName << ' ';
    out << "--" << opt.longName << (opt.kind == Kind::Option ? "=" : "");
  }
  out << "' -- \"$cur\") )\n"
         "        [[ ${COMPREPLY-} == *= ]] && compopt -o nospace\n"
         "        return\n"
         "    fi\n\n"
         "    _filedir '@("
      << ExtensionAlternation()
      << ")'\n"
         "} &&\n"
         "complete -F _wxmaxima";
  for (const auto &name : CommandNames)
    out << ' ' << name;
  out << "\n";
  return out.str();
}

//! \p text escaped for the [description] part of a zsh _arguments spec
std::string ZshDescription(std::string_view text) {
  return ReplaceAll(ReplaceAll(ReplaceAll(text, "\\", "\\\\"), "[", "\\["),
                    "]", "\\]");
}

std::string ZshAction(Complete what) {
  switch (what) {
  case Complete::Openable:
    return "_files -g \"*.(" + ExtensionAlternation() + ")(-.)\"";
  case Complete::AnyFile:
    return "_files";
  case Complete::Nothing:
    break;
  }
  return " ";
}

std::string Zsh() {
  std::ostringstream out;
  out << "#compdef";
  for (const auto &name : CommandNames)
    out << ' ' << name;
  out << "\n"
         "# zsh completion for wxmaxima(1).\n"
         "# Generated by wxmaxima-genopts from src/CommandLineOptions.h:\n"
         "# change the options there, not here.\n\n"
         "_arguments -s -S \\\n";
  for (const auto &opt : Options) {
    std::string spec;
    const bool takesValue = opt.kind == Kind::Option;
    const std::string longSpelling =
      "--" + std::string(opt.longName) + (takesValue ? "=" : "");
    if (opt.shortName.empty())
      spec = longSpelling;
    else {
      // "(-o --open)" makes either spelling exclude the other.
      const std::string shortSpelling =
        "-" + std::string(opt.shortName) + (takesValue ? "+" : "");
      out << "  " << ShellQuote("(-" + std::string(opt.shortName) + " --" +
                                std::string(opt.longName) + ")")
          << '{' << ShellQuote(shortSpelling) << ','
          << ShellQuote(longSpelling) << '}';
    }
    std::string rest = "[" + ZshDescription(opt.description) + "]";
    if (takesValue)
      rest += ":" + std::string(opt.valueName) + ":" + ZshAction(opt.complete);
    if (opt.shortName.empty())
      out << "  " << ShellQuote(spec + rest) << " \\\n";
    else
      out << ShellQuote(rest) << " \\\n";
  }
  out << "  "
      << ShellQuote("*:" + std::string(ParamDescription) + ":" +
                    ZshAction(Complete::Openable))
      << "\n";
  return out.str();
}

//! \p text as a single-quoted fish string
std::string FishQuote(std::string_view text) {
  return "'" + ReplaceAll(ReplaceAll(text, "\\", "\\\\"), "'", "\\'") + "'";
}

std::string Fish() {
  std::ostringstream out;
  out << "# fish completion for wxmaxima(1).\n"
         "# Generated by wxmaxima-genopts from src/CommandLineOptions.h:\n"
         "# change the options there, not here.\n\n";
  std::string extensions;
  for (const auto &ext : OpenableExtensions)
    extensions += " ." + std::string(ext);
  for (const auto &name : CommandNames) {
    for (const auto &opt : Options) {
      out << "complete -c " << name;
      if (!opt.shortName.empty())
        out << " -s " << opt.shortName;
      out << " -l " << opt.longName;
      if (opt.kind == Kind::Option) {
        switch (opt.complete) {
        case Complete::Openable:
        case Complete::AnyFile:
          out << " -r -F";
          break;
        case Complete::Nothing:
          out << " -x";
          break;
        }
      }
      out << " -d " << FishQuote(opt.description) << "\n";
    }
  }
  return out.str();
}

//! \p text escaped for roff. With \p minus, "-" becomes a minus sign, as an
//! option name needs to be for copy and paste; prose keeps its hyphens.
std::string Roff(std::string_view text, bool minus = false) {
  std::string result = ReplaceAll(text, "\\", "\\e");
  if (minus)
    result = ReplaceAll(result, "-", "\\-");
  // A line starting with "." or "'" would be read as a request.
  if (!result.empty() && (result[0] == '.' || result[0] == '\''))
    result.insert(0, "\\&");
  return result;
}

std::string ManOptions() {
  std::ostringstream out;
  out << ".\\\" Generated by wxmaxima-genopts from src/CommandLineOptions.h.\n";
  for (const auto &opt : Options) {
    out << ".TP\n";
    if (!opt.shortName.empty())
      out << "\\fB\\-" << Roff(opt.shortName, true) << "\\fR, ";
    out << "\\fB\\-\\-" << Roff(opt.longName, true) << "\\fR";
    if (opt.kind == Kind::Option)
      out << "=\\fI" << Roff(opt.valueName) << "\\fR";
    out << "\n" << Roff(opt.description) << "\n";
  }
  return out.str();
}

bool ReadFile(const std::string &name, std::string &contents) {
  std::ifstream in(name, std::ios::binary);
  if (!in)
    return false;
  std::ostringstream buffer;
  buffer << in.rdbuf();
  contents = buffer.str();
  return true;
}

//! Writes \p contents to \p name
bool WriteFile(const std::string &name, const std::string &contents) {
  std::ofstream out(name, std::ios::binary);
  out << contents;
  return static_cast<bool>(out);
}

constexpr std::string_view ManMarker = "WXMAXIMA-GENERATED-OPTIONS";

std::string Man(const std::string &templ) {
  std::istringstream in(templ);
  std::string line, result;
  bool replaced = false;
  while (std::getline(in, line)) {
    if (line.find(ManMarker) != std::string::npos) {
      result += ManOptions();
      replaced = true;
    } else
      result += line + "\n";
  }
  if (!replaced)
    return {};
  return result;
}

/*! Prints every long option a document does not mention; returns how many

  roff's font changes ("\fB") and other backslashes are dropped before
  searching, so "\fB\-\-open\fR" counts as "--open". An option must not be
  directly followed by more of a name, so "--debug" isn't found inside
  "--debugger".
*/
int CheckMentions(const std::string &name, const std::string &raw) {
  std::string text = raw;
  for (const std::string_view font : {"\\fB", "\\fI", "\\fR", "\\fP"})
    text = ReplaceAll(text, font, "");
  text = ReplaceAll(text, "\\", "");
  int missing = 0;
  for (const auto &opt : Options) {
    const std::string wanted = "--" + std::string(opt.longName);
    bool found = false;
    for (std::size_t pos = text.find(wanted); pos != std::string::npos;
         pos = text.find(wanted, pos + 1)) {
      const std::size_t after = pos + wanted.size();
      const char next = after < text.size() ? text[after] : ' ';
      if (!std::isalnum(static_cast<unsigned char>(next)) && next != '_' &&
          next != '-') {
        found = true;
        break;
      }
    }
    if (!found) {
      std::cerr << name << ": does not document " << wanted << "\n";
      ++missing;
    }
  }
  return missing;
}

int Usage() {
  std::cerr << "usage: wxmaxima-genopts bash|zsh|fish OUTFILE\n"
               "       wxmaxima-genopts man TEMPLATE OUTFILE\n"
               "       wxmaxima-genopts check FILE...\n";
  return 2;
}

} // namespace

int main(int argc, char *argv[]) {
  if (argc < 3)
    return Usage();
  const std::string_view mode = argv[1];
  std::string contents;
  if (mode == "bash" && argc == 3)
    contents = Bash();
  else if (mode == "zsh" && argc == 3)
    contents = Zsh();
  else if (mode == "fish" && argc == 3)
    contents = Fish();
  else if (mode == "man" && argc == 4) {
    std::string templ;
    if (!ReadFile(argv[2], templ)) {
      std::cerr << "wxmaxima-genopts: cannot read " << argv[2] << "\n";
      return 1;
    }
    contents = Man(templ);
    if (contents.empty()) {
      std::cerr << "wxmaxima-genopts: " << argv[2] << " has no line containing "
                << ManMarker << "\n";
      return 1;
    }
  } else if (mode == "check") {
    int missing = 0;
    for (int i = 2; i < argc; ++i) {
      std::string text;
      if (!ReadFile(argv[i], text)) {
        std::cerr << "wxmaxima-genopts: cannot read " << argv[i] << "\n";
        return 1;
      }
      missing += CheckMentions(argv[i], text);
    }
    if (missing > 0) {
      std::cerr << missing
                << " option(s) undocumented. Each option in "
                   "src/CommandLineOptions.h has to be described in the "
                   "files above.\n";
      return 1;
    }
    return 0;
  } else
    return Usage();

  const std::string outFile = argv[argc - 1];
  if (!WriteFile(outFile, contents)) {
    std::cerr << "wxmaxima-genopts: cannot write " << outFile << "\n";
    return 1;
  }
  return 0;
}
